package com.realestate.app.ui.theme

import androidx.compose.ui.unit.dp

/** 8pt spacing system shared by every screen — keeps padding and gaps consistent app-wide. */
object Spacing {
    val xs = 4.dp
    val sm = 8.dp
    val md = 12.dp
    val lg = 16.dp
    val xl = 24.dp
    val xxl = 32.dp

    /** Outer screen padding. */
    val screen = 24.dp

    /** Vertical gap between stacked cards. */
    val cardGap = 16.dp

    /** Inner padding applied inside a card. */
    val cardPadding = 20.dp
}
